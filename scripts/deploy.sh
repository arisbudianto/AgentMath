#!/bin/bash
# Standard production deploy: syncs a git checkout (this repo, already `git pull`ed to
# the target commit) into the live cPanel docroot via rsync, with an exclude list that
# protects server-managed and environment-specific files from ever being overwritten.
#
# This script does NOT run `git pull`, `composer install`, or database migrations —
# those are separate, deliberate steps (see docs/DEPLOYMENT.md). It only answers the
# question "how do I safely copy the checkout into production", which was previously
# done ad hoc with no recorded exclude list.
#
# Usage:
#   bash scripts/deploy.sh [--dry-run] <source_checkout_dir> <production_docroot_dir>
#
# Example (paths used by this project on veleta.id.rapidplex.com):
#   bash scripts/deploy.sh ~/agentmath-m00 ~/math.speakverse.id
#   bash scripts/deploy.sh --dry-run ~/agentmath-m00 ~/math.speakverse.id   # preview only, changes nothing
#
# Preconditions (not checked by this script — verify manually first):
#   - The source checkout is on the commit that passed CI (`git log -1`, `git status -s` clean).
#   - `composer install --no-dev --prefer-dist --no-interaction --optimize-autoloader`
#     has been run in the source checkout, so vendor/ is current for the new code.
#   - If this deploy includes migrations, `php artisan migrate --pretend` in the
#     source checkout has been reviewed and backups/risk are accounted for
#     (this script does not run migrations).
#
# After this script finishes, the standard post-deploy steps are still manual:
#   cd <production_docroot_dir>
#   php artisan config:cache && php artisan view:cache
#   # review `php artisan migrate --pretend` before running `php artisan migrate`
#   bash scripts/verify-public-home.sh <production_docroot_dir> https://math.speakverse.id
#   curl -s https://math.speakverse.id/health
#
# OS lock: per docs/DEPLOYMENT.md, M04's grading worker reads
# /home/speakver/.agentmath-grading.lock during maintenance so it never loads mixed
# code. This script holds that lock for the duration of the rsync.

set -euo pipefail

LOCK_FILE="${AGENTMATH_DEPLOY_LOCK:-$HOME/.agentmath-grading.lock}"

dry_run=0
if [[ "${1:-}" == "--dry-run" ]]; then
    dry_run=1
    shift
fi

source_dir=${1:?Usage: bash scripts/deploy.sh [--dry-run] <source_checkout_dir> <production_docroot_dir>}
target_dir=${2:?Usage: bash scripts/deploy.sh [--dry-run] <source_checkout_dir> <production_docroot_dir>}

source_dir=${source_dir%/}
target_dir=${target_dir%/}

test -f "$source_dir/artisan" || { echo "Not a Laravel app root: $source_dir" >&2; exit 1; }
test -f "$target_dir/artisan" || { echo "Not a Laravel app root (refusing to deploy into an unrelated directory): $target_dir" >&2; exit 1; }

# Exclude list, derived from the actual diff between the git checkout and the live
# docroot on 2026-10-26:
#   - .git, .github            : repo/CI metadata, not part of the running app.
#   - .env                     : production secrets; never overwritten by a deploy.
#   - storage                  : persistent uploads, logs, framework cache — per-server state.
#   - bootstrap/cache          : regenerated by `artisan config:cache`/`view:cache`, not synced.
#   - vendor                   : installed separately with `composer install --no-dev` in the
#                                 source checkout; not synced wholesale (keeps prod vendor/
#                                 reproducible from composer.lock rather than from rsync state).
#   - public/.htaccess         : cPanel prepends auto-generated PHP ini directives to this
#                                 file on the server; syncing it from git would silently strip
#                                 that cPanel-managed block and can break the PHP version/error
#                                 log config for the vhost. Confirmed by diffing the two files.
#   - public/php.ini           : cPanel/EA4 PHP handler config, server-specific.
#   - public/.user.ini         : PHP per-directory ini override, server-specific.
#   - public/.well-known       : ACME/TLS challenge files managed by the host, not the repo.
#   - .gitignore                : local-checkout-only, not needed by the running app.
EXCLUDES=(
    --exclude=.git
    --exclude=.github
    --exclude=.gitignore
    --exclude=.env
    --exclude=storage
    --exclude=bootstrap/cache
    --exclude=vendor
    --exclude=public/.htaccess
    --exclude=public/php.ini
    --exclude=public/.user.ini
    --exclude=public/.well-known
)

RSYNC_FLAGS=(-a --delete --itemize-changes "${EXCLUDES[@]}")
if [[ $dry_run -eq 1 ]]; then
    RSYNC_FLAGS+=(--dry-run)
    echo "DRY RUN — no files will be changed. Review the list below, then rerun without --dry-run."
fi

run_rsync() {
    rsync "${RSYNC_FLAGS[@]}" "$source_dir/" "$target_dir/"
}

if [[ $dry_run -eq 1 ]]; then
    run_rsync
    exit 0
fi

echo "Acquiring deploy lock at $LOCK_FILE ..."
exec 9>"$LOCK_FILE"
flock -w 60 9 || { echo "Could not acquire $LOCK_FILE within 60s (grading worker or another deploy holding it?)" >&2; exit 1; }

echo "Lock acquired. Syncing $source_dir/ -> $target_dir/ ..."
run_rsync
sync_status=$?

flock -u 9
echo "Lock released."

if [[ $sync_status -ne 0 ]]; then
    echo "rsync failed with status $sync_status" >&2
    exit "$sync_status"
fi

echo "Sync complete. Next (manual, not run by this script):"
echo "  cd $target_dir && php artisan config:cache && php artisan view:cache"
echo "  review: php artisan migrate --pretend   (run php artisan migrate only after reviewing)"
echo "  curl -s https://math.speakverse.id/health"
